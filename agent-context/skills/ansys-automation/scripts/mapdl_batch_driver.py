# -*- coding: utf-8 -*-
"""DDS template - classic MAPDL batch driver (tool key: python, platform venv; py2/py3 compatible).

Flow  : params.json -> params.inp (APDL "NAME=value") -> MAPDL -b -i <template> -o solve.out
        -> dds_results.txt -> results.json ; *.png from /SHOW,PNG -> images/
Run   : python mapdl_batch_driver.py --template plate_template.inp [--mapdl EXE] [--np 2] [--jobname file]
        MAPDL executable: --mapdl or env DDS_ANSYS_MAPDL (e.g. C:/Program Files/ANSYS Inc/v242/ansys/bin/winx64/ANSYS242.exe)
Template contract: APDL input that does /INPUT,params,inp and writes "key value" lines to
        dds_results.txt via *CFOPEN/*VWRITE (see plate_template.inp).
"""
import argparse
import glob
import json
import os
import re
import shutil
import subprocess
import sys

APDL_NAME = re.compile(r"^[A-Za-z][A-Za-z0-9_]{0,31}$")


def write_params_inp(params, path):
    lines = ["! generated by mapdl_batch_driver.py from params.json"]
    for key in sorted(params):
        name = key.upper()
        if not APDL_NAME.match(name) or name.endswith("_"):
            raise ValueError("invalid APDL parameter name: %s" % key)
        value = params[key]
        if isinstance(value, (int, float)):
            lines.append("%s=%.12g" % (name, float(value)))
        else:
            # character parameter (max 8 chars for 'string' assignment)
            lines.append("%s='%s'" % (name, str(value)[:8]))
    with open(path, "w") as f:
        f.write("\n".join(lines) + "\n")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--template", required=True)
    ap.add_argument("--mapdl", default=os.environ.get("DDS_ANSYS_MAPDL"))
    ap.add_argument("--np", type=int, default=2)
    ap.add_argument("--jobname", default="file")
    ap.add_argument("--allow-errors", action="store_true",
                    help="accept results even if solve.out contains *** ERROR ***")
    args = ap.parse_args()
    if not args.mapdl:
        raise SystemExit("MAPDL executable not given (--mapdl or env DDS_ANSYS_MAPDL)")

    case_dir = os.getcwd()
    res_path = os.path.join(case_dir, "results.json")
    txt_path = os.path.join(case_dir, "dds_results.txt")
    for p in (res_path, txt_path):
        if os.path.exists(p):
            os.remove(p)

    with open(os.path.join(case_dir, "params.json"), "r") as f:
        params = json.load(f)
    write_params_inp(params, os.path.join(case_dir, "params.inp"))

    template = os.path.abspath(args.template)
    local_tpl = os.path.join(case_dir, os.path.basename(template))
    if template != local_tpl:
        shutil.copy(template, local_tpl)

    cmd = [args.mapdl, "-b", "-np", str(args.np), "-j", args.jobname,
           "-dir", case_dir, "-i", os.path.basename(local_tpl), "-o", "solve.out"]
    print("[DDS] run: %s" % " ".join(cmd))
    rc = subprocess.call(cmd, cwd=case_dir)
    print("[DDS] MAPDL exit code: %s" % rc)   # TODO(사내검증): exit code meaning per version

    out_txt = ""
    out_file = os.path.join(case_dir, "solve.out")
    if os.path.exists(out_file):
        with open(out_file, "r") as f:
            out_txt = f.read()
    n_err = out_txt.count("*** ERROR ***")
    if n_err:
        print("[DDS] %d '*** ERROR ***' in solve.out (see also %s.err)" % (n_err, args.jobname))
        if not args.allow_errors:
            sys.exit(4)

    if not os.path.exists(txt_path):
        print("[DDS] dds_results.txt missing -> case failed")
        sys.exit(2)

    res = {}
    with open(txt_path, "r") as f:
        for line in f:
            parts = line.split()
            if len(parts) == 2:
                res[parts[0].lower()] = float(parts[1])
    if not res:
        print("[DDS] no values in dds_results.txt")
        sys.exit(3)

    img_dir = os.path.join(case_dir, "images")
    if not os.path.isdir(img_dir):
        os.makedirs(img_dir)
    for png in sorted(glob.glob(os.path.join(case_dir, args.jobname + "*.png"))):
        shutil.move(png, os.path.join(img_dir, os.path.basename(png)))

    with open(res_path, "w") as f:
        json.dump(res, f, indent=2, sort_keys=True)
    print("[DDS] results: %s" % json.dumps(res))


if __name__ == "__main__":
    main()
